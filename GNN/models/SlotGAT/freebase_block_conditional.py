def local_relation_matrix(
    *,
    pairs: tuple[np.ndarray, np.ndarray],
    relation: RelationInfo,
    layout: NodeTypeLayout,
) -> sp.csr_matrix:
    source, destination = pairs
    source_offset = layout.offsets[relation.start_type]
    destination_offset = layout.offsets[relation.end_type]
    local_source = source - int(source_offset)
    local_destination = destination - int(destination_offset)
    if np.any(local_source < 0) or np.any(
        local_source >= layout.counts[relation.start_type]
    ):
        raise ValueError(f"Source type mismatch in relation {relation.name}")
    if np.any(local_destination < 0) or np.any(
        local_destination >= layout.counts[relation.end_type]
    ):
        raise ValueError(f"Destination type mismatch in relation {relation.name}")
    matrix = sp.coo_matrix(
        (
            np.ones(source.size, dtype=bool),
            (local_source, local_destination),
        ),
        shape=(
            layout.counts[relation.start_type],
            layout.counts[relation.end_type],
        ),
    ).tocsr()
    matrix.sum_duplicates()
    if matrix.nnz:
        matrix.data[:] = 1
    matrix.eliminate_zeros()
    matrix.sort_indices()
    return matrix


def binarize(matrix: sp.spmatrix) -> sp.csr_matrix:
    result = matrix.tocsr(copy=True)
    result.sum_duplicates()
    if result.nnz:
        result.data[:] = 1
    result.eliminate_zeros()
    result.sort_indices()
    return result


def boolean_compose(left: sp.spmatrix, right: sp.spmatrix) -> sp.csr_matrix:
    if left.shape[1] != right.shape[0]:
        raise ValueError(f"Composition shape mismatch: {left.shape} @ {right.shape}")
    return binarize(left.astype(bool) @ right.astype(bool))


def csr_pair_fingerprint(
    matrix: sp.csr_matrix,
    source_globals: np.ndarray,
    destination_globals: np.ndarray,
) -> dict[str, int]:
    result = empty_fingerprint()
    for start in range(0, matrix.shape[0], 4096):
        stop = min(matrix.shape[0], start + 4096)
        counts = np.diff(matrix.indptr[start : stop + 1])
        if not np.any(counts):
            continue
        local_rows = np.repeat(np.arange(start, stop, dtype=np.int64), counts)
        local_columns = matrix.indices[matrix.indptr[start] : matrix.indptr[stop]]
        update_fingerprint(
            result,
            source_globals[local_rows],
            destination_globals[local_columns],
        )
    return result


def _sparse_edge_metrics(predicted: sp.csr_matrix, truth: sp.csr_matrix) -> dict[str, Any]:
    predicted = binarize(predicted)
    truth = binarize(truth)
    intersection = predicted.multiply(truth)
    true_positive = int(intersection.nnz)
    false_positive = int(predicted.nnz - true_positive)
    false_negative = int(truth.nnz - true_positive)
    precision = (
        true_positive / (true_positive + false_positive)
        if true_positive + false_positive
        else 0.0
    )
    recall = (
        true_positive / (true_positive + false_negative)
        if true_positive + false_negative
        else 0.0
    )
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "tp": true_positive,
        "fp": false_positive,
        "fn": false_negative,
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "pred_edge_count": int(predicted.nnz),
        "true_edge_count": int(truth.nnz),
    }


def canonical_block_edge_set(
    matrix: sp.csr_matrix,
) -> set[tuple[tuple[int, ...], tuple[int, ...]]]:
    """Match the miner's canonical block-edge representation exactly.

    This deliberately discards row/column membership multiplicities.  It is not
    an endpoint biclique decomposition.
    """
    matrix = binarize(matrix)
    row_nonzero = np.diff(matrix.indptr)
    column_matrix = matrix.tocsc()
    column_nonzero = np.diff(column_matrix.indptr)
    row_signature_by_row = {
        int(row): tuple(
            int(value)
            for value in matrix.indices[matrix.indptr[row] : matrix.indptr[row + 1]]
        )
        for row in np.flatnonzero(row_nonzero > 0)
    }
    column_signature_by_column = {
        int(column): tuple(
            int(value)
            for value in column_matrix.indices[
                column_matrix.indptr[column] : column_matrix.indptr[column + 1]
            ]
        )
        for column in np.flatnonzero(column_nonzero > 0)
    }
    result: set[tuple[tuple[int, ...], tuple[int, ...]]] = set()
    for row, row_signature in row_signature_by_row.items():
        columns = matrix.indices[matrix.indptr[row] : matrix.indptr[row + 1]]
        for column in columns:
            column_signature = column_signature_by_column.get(int(column))
            if column_signature is not None:
                result.add((row_signature, column_signature))
    return result


def _block_metrics(
    predicted: sp.csr_matrix,
    truth: sp.csr_matrix,
) -> dict[str, Any]:
    predicted_blocks = canonical_block_edge_set(predicted)
    truth_blocks = canonical_block_edge_set(truth)
    true_positive = len(predicted_blocks & truth_blocks)
    false_positive = len(predicted_blocks - truth_blocks)
    false_negative = len(truth_blocks - predicted_blocks)
    precision = (
        true_positive / (true_positive + false_positive)
        if true_positive + false_positive
        else 0.0
    )
    recall = (
        true_positive / (true_positive + false_negative)
        if true_positive + false_negative
        else 0.0
    )
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "tp": int(true_positive),
        "fp": int(false_positive),
        "fn": int(false_negative),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "pred_block_edge_count": int(len(predicted_blocks)),
        "true_block_edge_count": int(len(truth_blocks)),
    }


def construct_block_relations(
    *,
    registry_rows: Sequence[Mapping[str, Any]],
    base_relations: Mapping[str, RelationInfo],
    base_pairs: Mapping[str, tuple[np.ndarray, np.ndarray]],
    channels: Sequence[ChannelRecord],
    layout: NodeTypeLayout,
) -> tuple[BlockRelation, ...]:
    """Create factorized semantic paths from the authoritative registry.

    The supplied MAGNN registry records an ordered base-relation composition
    for each materialized shortcut.  It does *not* contain endpoint quotient
    memberships, and endpoint block bijectivity is not required here.  We
    therefore validate type continuity, derive endpoint support by sparse
    reachability, and use the physical shortcut count as the scalable
    composition audit.  No shortcut endpoint matrix is materialized.
    """
    channel_lookup = {
        (record.semantic_relation, record.direction): int(record.channel)
        for record in channels
    }
    matrix_cache: dict[str, sp.csr_matrix] = {}

    def relation_matrix(name: str) -> sp.csr_matrix:
        cached = matrix_cache.get(name)
        if cached is None:
            if name not in base_relations:
                raise KeyError(f"Mapping references unknown base relation {name!r}")
            cached = local_relation_matrix(
                pairs=base_pairs[name], relation=base_relations[name], layout=layout
            )
            matrix_cache[name] = cached
        return cached

    def composition_types(sequence: Sequence[str]) -> tuple[int, int]:
        if not sequence:
            raise ValueError("A conditional composition cannot be empty")
        first = base_relations[sequence[0]]
        current_type = int(first.end_type)
        for component in sequence[1:]:
            specification = base_relations[component]
            if current_type != int(specification.start_type):
                raise ValueError(
                    f"Type-discontinuous composition {sequence}: expected start "
                    f"type {current_type}, found {specification.start_type} for {component}"
                )
            current_type = int(specification.end_type)
        return int(first.start_type), current_type

    def endpoint_support(
        sequence: Sequence[str], start_type: int, end_type: int
    ) -> tuple[np.ndarray, np.ndarray]:
        # Destination nodes reachable from at least one valid source path.
        forward = np.ones(layout.counts[start_type], dtype=np.uint8)
        for component in sequence:
            matrix = relation_matrix(component).astype(np.uint8)
            forward = np.asarray(forward @ matrix).reshape(-1)
            forward = (forward > 0).astype(np.uint8)
        forward_local = np.flatnonzero(forward > 0).astype(np.int64)

        # Source nodes from which at least one valid destination is reachable.
        reverse = np.ones(layout.counts[end_type], dtype=np.uint8)
        for component in reversed(sequence):
            matrix = relation_matrix(component).astype(np.uint8)
            reverse = np.asarray(matrix @ reverse).reshape(-1)
            reverse = (reverse > 0).astype(np.uint8)
        reverse_local = np.flatnonzero(reverse > 0).astype(np.int64)
        return (
            layout.global_nodes(end_type)[forward_local],
            layout.global_nodes(start_type)[reverse_local],
        )

    results: list[BlockRelation] = []
    for row in sorted(registry_rows, key=lambda item: str(item["new_relation_name"])):
        name = str(row["new_relation_name"])
        composition = tuple(str(value) for value in row["composition_list"])
        try:
            start_type, end_type = composition_types(composition)
            declared_start = row.get("start_type_id")
            declared_end = row.get("end_type_id")
            if declared_start is not None and int(declared_start) != start_type:
                raise ValueError(
                    f"Registry start type mismatch: declared={declared_start}, computed={start_type}"
                )
            if declared_end is not None and int(declared_end) != end_type:
                raise ValueError(
                    f"Registry end type mismatch: declared={declared_end}, computed={end_type}"
                )

            forward_support, reverse_support = endpoint_support(
                composition, start_type, end_type
            )
            if forward_support.size == 0 or reverse_support.size == 0:
                raise ValueError("The registered composition has empty endpoint support")

            expected_count = int(
                row.get("unique_endpoint_pairs", row.get("num_new_edges", -1))
            )
            if expected_count <= 0:
                raise ValueError(
                    f"Registry does not provide a positive endpoint count for {name}"
                )

            # Recovery metadata is retained as provenance only.  The attached
            # registry does not encode quotient memberships or per-position
            # recovery tables, so preprocessing must not invent or re-impose a
            # different endpoint-block criterion.
            recovery_provenance = tuple(
                {
                    "drop_index": int(index),
                    "dropped_relation": component,
                    "status": "registry_authoritative_not_recomputed",
                }
                for index, component in enumerate(composition)
            )
            results.append(
                BlockRelation(
                    name=name,
                    composition=composition,
                    start_type=start_type,
                    end_type=end_type,
                    forward_channel=channel_lookup[(name, 1)],
                    reverse_channel=channel_lookup[(name, -1)],
                    forward_steps=tuple(
                        channel_lookup[(component, 1)] for component in composition
                    ),
                    reverse_steps=tuple(
                        channel_lookup[(component, -1)]
                        for component in reversed(composition)
                    ),
                    forward_support=np.asarray(forward_support, dtype=np.int64),
                    reverse_support=np.asarray(reverse_support, dtype=np.int64),
                    endpoint_count=expected_count,
                    endpoint_fingerprint={
                        "count": expected_count,
                        "xor64": 0,
                        "sum64": 0,
                    },
                    hop_recovery=recovery_provenance,
                )
            )
        except Exception as error:
            raise ValueError(
                f"Failed conditional mapping {name} with composition {composition}: {error}"
            ) from error
    return tuple(results)


