def parse_info(path: Path) -> tuple[dict[int, str], dict[int, RelationInfo]]:
    node_types: dict[int, str] = {}
    relations: dict[int, RelationInfo] = {}
    section: str | None = None
    with Path(path).open("r", encoding="utf-8") as handle:
        for raw in handle:
            text = raw.strip()
            if not text:
                continue
            if text == "node.dat":
                section = "node"
                continue
            if text == "link.dat":
                section = "link"
                continue
            if text in {"label.dat", "label.dat.test"}:
                section = "label"
                continue
            if text.startswith(
                ("TYPE\t", "LINK\t", "Attribute Dimension:", "Targeting:", "---")
            ):
                continue
            parts = [part for part in text.split("\t") if part != ""]
            if section == "node" and len(parts) >= 2:
                node_types[int(parts[0])] = parts[-1]
            elif section == "link" and len(parts) >= 4:
                rid = int(parts[0])
                relations[rid] = RelationInfo(
                    rid=rid,
                    start_type=int(parts[1]),
                    end_type=int(parts[2]),
                    name=parts[-1],
                )
    if not relations:
        raise ValueError(f"No relation schema was found in {path}")
    return node_types, relations


def read_registry(path: Path) -> list[dict[str, Any]]:
    rows = []
    with Path(path).open("r", encoding="utf-8") as handle:
        for line_no, raw in enumerate(handle, 1):
            if not raw.strip():
                continue
            row = json.loads(raw)
            if str(row.get("skipped_reason", "")).strip():
                continue
            name = str(row.get("new_relation_name", "")).strip()
            composition = tuple(
                token.strip()
                for token in str(row.get("composition", "")).split(";")
                if token.strip()
            )
            if not name or len(composition) < 2:
                raise ValueError(f"Malformed registry row at {path}:{line_no}")
            normalized = dict(row)
            normalized["new_relation_name"] = name
            normalized["composition_list"] = list(composition)
            rows.append(normalized)
    if not rows:
        raise ValueError(f"No usable mappings were found in {path}")
    return rows


def read_node_layout(node_path: Path, node_type_names: Mapping[int, str]) -> NodeTypeLayout:
    by_type: dict[int, list[int]] = defaultdict(list)
    maximum = -1
    with Path(node_path).open("r", encoding="utf-8") as handle:
        for line_no, raw in enumerate(handle, 1):
            if not raw.strip():
                continue
            parts = raw.rstrip("\n").split("\t")
            if len(parts) < 3:
                raise ValueError(f"Bad node.dat line {line_no}: {raw!r}")
            node, node_type = int(parts[0]), int(parts[2])
            by_type[node_type].append(node)
            maximum = max(maximum, node)
    type_ids = sorted(node_type_names)
    if type_ids != list(range(len(type_ids))):
        raise ValueError("Freebase node-type IDs must be dense from zero")
    counts: list[int] = []
    offsets: list[int] = []
    expected = 0
    for node_type in type_ids:
        nodes = sorted(by_type[node_type])
        offsets.append(expected)
        counts.append(len(nodes))
        desired = list(range(expected, expected + len(nodes)))
        if nodes != desired:
            raise ValueError(
                "The SlotGAT Freebase implementation requires nodes to be contiguous "
                f"by type; type={node_type} begins with {nodes[:5]}, expected {desired[:5]}"
            )
        expected += len(nodes)
    if expected != maximum + 1:
        raise ValueError("node.dat IDs are not globally contiguous")
    return NodeTypeLayout(
        counts=tuple(counts),
        offsets=tuple(offsets),
        names=tuple(node_type_names[index] for index in type_ids),
    )


def channel_catalog(
    base_relations: Mapping[str, RelationInfo],
    registry_rows: Sequence[Mapping[str, Any]],
) -> tuple[ChannelRecord, ...]:
    records: list[ChannelRecord] = []
    for name in sorted(base_relations):
        records.append(ChannelRecord(len(records), name, 1, "base_relation"))
        records.append(ChannelRecord(len(records), name, -1, "base_relation"))
    for row in sorted(registry_rows, key=lambda item: str(item["new_relation_name"])):
        name = str(row["new_relation_name"])
        records.append(ChannelRecord(len(records), name, 1, "conditional_path"))
        records.append(ChannelRecord(len(records), name, -1, "conditional_path"))
    records.append(ChannelRecord(len(records), "__self__", 0, "self"))
    return tuple(records)


