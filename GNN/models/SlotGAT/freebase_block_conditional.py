def _semantic_hash(
    *,
    channels: Sequence[ChannelRecord],
    base_src: np.ndarray,
    base_dst: np.ndarray,
    base_channel: np.ndarray,
    block_relations: Sequence[BlockRelation],
    layout: NodeTypeLayout,
) -> str:
    return sha256_json(
        {
            "layout": layout.to_json(),
            "channels": [record.to_json() for record in channels],
            "base_src": sha256_array(base_src),
            "base_dst": sha256_array(base_dst),
            "base_channel": sha256_array(base_channel),
            "mappings": [relation.semantic_descriptor() for relation in block_relations],
            "operator": "factorized_recoverability_conditional_slotgat_v2",
        }
    )


def preprocess_pair(
    *,
    unchanged_dir: Path,
    exact_dir: Path,
    registry_path: Path,
    output_root: Path,
    overwrite: bool = False,
) -> dict[str, Any]:
    unchanged_dir = Path(unchanged_dir).resolve()
    exact_dir = Path(exact_dir).resolve()
    registry_path = Path(registry_path).resolve()
    output_root = Path(output_root).resolve()
    if output_root.exists() and any(output_root.iterdir()):
        if not overwrite:
            raise FileExistsError(
                f"Output directory is nonempty; pass --overwrite: {output_root}"
            )
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True, exist_ok=True)

    unchanged_node_names, unchanged_relations_by_id = parse_info(
        unchanged_dir / "info.dat"
    )
    exact_node_names, exact_relations_by_id = parse_info(exact_dir / "info.dat")
    if unchanged_node_names != exact_node_names:
        raise ValueError("Node-type schemas differ across Freebase variants")
    layout = read_node_layout(unchanged_dir / "node.dat", unchanged_node_names)
    exact_layout = read_node_layout(exact_dir / "node.dat", exact_node_names)
    if layout != exact_layout:
        raise ValueError("Node layouts differ across Freebase variants")
    if sha256_file(unchanged_dir / "node.dat") != sha256_file(exact_dir / "node.dat"):
        raise ValueError("node.dat differs across Freebase variants")
    if sha256_file(unchanged_dir / "label.dat") != sha256_file(exact_dir / "label.dat"):
        raise ValueError("label.dat differs across Freebase variants")

    base_relations = {
        relation.name: relation for relation in unchanged_relations_by_id.values()
    }
    registry_rows = read_registry(registry_path)
    shortcut_names = {str(row["new_relation_name"]) for row in registry_rows}
    exact_relations = {
        relation.name: relation for relation in exact_relations_by_id.values()
    }
    missing_shortcuts = sorted(shortcut_names - set(exact_relations))
    if missing_shortcuts:
        raise ValueError(
            "The changed graph schema is missing registry shortcut relations: "
            + ", ".join(missing_shortcuts[:10])
        )
    for name, relation in base_relations.items():
        other = exact_relations.get(name)
        if other is None or (other.start_type, other.end_type) != (
            relation.start_type,
            relation.end_type,
        ):
            raise ValueError(f"Base relation schema differs for {name}")

    unchanged_pairs, unchanged_base_fingerprint, unchanged_shortcut_fingerprint = (
        read_variant_edges(
            link_path=unchanged_dir / "link.dat",
            relations=unchanged_relations_by_id,
            base_names=set(base_relations),
            shortcut_names=shortcut_names,
        )
    )
    exact_pairs, exact_base_fingerprint, exact_shortcut_fingerprint = read_variant_edges(
        link_path=exact_dir / "link.dat",
        relations=exact_relations_by_id,
        base_names=set(base_relations),
        shortcut_names=shortcut_names,
    )
    if unchanged_base_fingerprint != exact_base_fingerprint:
        differing = [
            name
            for name in sorted(base_relations)
            if unchanged_base_fingerprint.get(name)
            != exact_base_fingerprint.get(name)
        ]
        raise ValueError(
            "Changed graph does not preserve the unchanged base relations: "
            + ", ".join(differing[:10])
        )

    channels = channel_catalog(base_relations, registry_rows)
    mappings = construct_block_relations(
        registry_rows=registry_rows,
        base_relations=base_relations,
        base_pairs=unchanged_pairs,
        channels=channels,
        layout=layout,
    )

    for mapping in mappings:
        physical = exact_shortcut_fingerprint.get(
            mapping.name, empty_fingerprint()
        )
        if int(physical.get("count", 0)) != int(mapping.endpoint_count):
            raise ValueError(
                f"Physical shortcut count mismatch for {mapping.name}: "
                f"physical={physical.get('count', 0)}, registry={mapping.endpoint_count}"
            )
        if int(
            unchanged_shortcut_fingerprint.get(
                mapping.name, empty_fingerprint()
            )["count"]
        ) != 0:
            raise ValueError(
                f"Unchanged graph unexpectedly contains shortcut relation {mapping.name}"
            )

    plan_records = []
    semantic_hashes: set[str] = set()
    raw_hashes: set[str] = set()
    context_hashes: set[str] = set()
    for variant, data_dir, context_kind, pairs, base_fingerprint, shortcut_fingerprint in (
        (
            "unchanged",
            unchanged_dir,
            "base_composition",
            unchanged_pairs,
            unchanged_base_fingerprint,
            unchanged_shortcut_fingerprint,
        ),
        (
            registry_path.stem,
            exact_dir,
            "physical_shortcut",
            exact_pairs,
            exact_base_fingerprint,
            exact_shortcut_fingerprint,
        ),
    ):
        base_src, base_dst, base_channel = build_base_message_arrays(
            base_pairs=pairs,
            channels=channels,
            total_nodes=layout.total,
        )
        semantic_program_hash = _semantic_hash(
            channels=channels,
            base_src=base_src,
            base_dst=base_dst,
            base_channel=base_channel,
            block_relations=mappings,
            layout=layout,
        )
        raw_graph_hash = combined_raw_graph_hash(data_dir)
        raw_link_hash = sha256_file(data_dir / "link.dat")
        context_payload = {
            "variant": variant,
            "context_kind": context_kind,
            "raw_graph_hash": raw_graph_hash,
            "raw_link_hash": raw_link_hash,
            "base_graph_hash": base_graph_hash(base_fingerprint),
            "physical_shortcuts": shortcut_fingerprint,
            "semantic_program_hash": semantic_program_hash,
            "mapping_contexts": {
                mapping.name: {
                    "composition": list(mapping.composition),
                    "activation": context_kind,
                }
                for mapping in mappings
            },
        }
        context_plan_hash = sha256_json(context_payload)
        plan = FreebaseBlockContextPlan(
            variant=variant,
            context_kind=context_kind,
            layout=layout,
            channels=channels,
            base_src=base_src,
            base_dst=base_dst,
            base_channel=base_channel,
            block_relations=mappings,
            raw_graph_hash=raw_graph_hash,
            raw_link_hash=raw_link_hash,
            base_graph_hash=base_graph_hash(base_fingerprint),
            physical_shortcut_fingerprints=shortcut_fingerprint,
            semantic_program_hash=semantic_program_hash,
            context_plan_hash=context_plan_hash,
            source_dir=str(data_dir),
        )
        plan.verify_runtime_context()
        plan.save(output_root / variant)
        record = plan.audit_dict()
        plan_records.append(record)
        semantic_hashes.add(semantic_program_hash)
        raw_hashes.add(raw_graph_hash)
        context_hashes.add(context_plan_hash)

    passed = (
        len(raw_hashes) == 2
        and len(context_hashes) == 2
        and len(semantic_hashes) == 1
    )
    audit = {
        "passed": passed,
        "registry_path": str(registry_path),
        "registry_sha256": sha256_file(registry_path),
        "mapping_interpretation": "authoritative_ordered_composition_with_block_recoverability_provenance",
        "endpoint_block_bijection_required": False,
        "endpoint_quotient_materialized": False,
        "physical_verification": "registry_count",
        "physical_shortcuts_used_as_context_only": True,
        "factorized_dependency_used_for_propagation": True,
        "plans": plan_records,
    }
    write_json(output_root / "preprocessing_audit.json", audit)
    if not passed:
        raise AssertionError(f"Freebase recoverability preprocessing failed: {audit}")
    return audit


def preprocess_family(
    *,
    unchanged_dir: Path,
    changed_dirs: Mapping[str, Path],
    registry_paths: Sequence[Path],
    output_root: Path,
    overwrite: bool = False,
) -> dict[str, Any]:
    """Family generalisation of :func:`preprocess_pair`.

    One shared channel catalog and ONE semantic program for the whole family
    {unchanged} U changed_dirs (e.g. exact_2, exact_3, union_exact_2_3), built from the
    concatenation of every registry (2-hop + 3-hop compositions). The semantic program
    depends only on the base edges and the registry, so it is identical for every
    variant by construction; each variant's plan differs in raw hashes and in which
    shortcut relations it physically carries (``physical_shortcut_names``), which
    ``verify_runtime_context`` checks per variant. The universal graph is simply the
    changed variant whose schema declares every shortcut (``union_exact_2_3``).
    """
    unchanged_dir = Path(unchanged_dir).resolve()
    changed = {str(name): Path(path).resolve() for name, path in changed_dirs.items()}
    if not changed:
        raise ValueError("preprocess_family needs at least one changed variant")
    output_root = Path(output_root).resolve()
    if output_root.exists() and any(output_root.iterdir()):
        if not overwrite:
            raise FileExistsError(
                f"Output directory is nonempty; pass --overwrite: {output_root}"
            )
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True, exist_ok=True)

    unchanged_node_names, unchanged_relations_by_id = parse_info(unchanged_dir / "info.dat")
    layout = read_node_layout(unchanged_dir / "node.dat", unchanged_node_names)
    base_relations = {r.name: r for r in unchanged_relations_by_id.values()}

    registry_rows: list[dict[str, Any]] = []
    seen_names: set[str] = set()
    for path in registry_paths:
        for row in read_registry(Path(path)):
            name = str(row["new_relation_name"])
            if name in seen_names:
                raise ValueError(f"Shortcut relation {name} appears in more than one registry")
            seen_names.add(name)
            row["registry_path"] = str(Path(path).resolve())
            registry_rows.append(row)
    shortcut_names = set(seen_names)

    variant_info: dict[str, tuple[Path, dict[int, RelationInfo], set[str]]] = {}
    for name, data_dir in changed.items():
        node_names, relations_by_id = parse_info(data_dir / "info.dat")
        if node_names != unchanged_node_names:
            raise ValueError(f"Node-type schemas differ: unchanged vs {name}")
        if read_node_layout(data_dir / "node.dat", node_names) != layout:
            raise ValueError(f"Node layouts differ: unchanged vs {name}")
        if sha256_file(unchanged_dir / "node.dat") != sha256_file(data_dir / "node.dat"):
            raise ValueError(f"node.dat differs: unchanged vs {name}")
        if sha256_file(unchanged_dir / "label.dat") != sha256_file(data_dir / "label.dat"):
            raise ValueError(f"label.dat differs: unchanged vs {name}")
        relations = {r.name: r for r in relations_by_id.values()}
        for base_name, relation in base_relations.items():
            other = relations.get(base_name)
            if other is None or (other.start_type, other.end_type) != (relation.start_type, relation.end_type):
                raise ValueError(f"Base relation schema differs for {base_name} in {name}")
        declared = {r for r in relations if r not in base_relations}
        unknown = sorted(declared - shortcut_names)
        if unknown:
            raise ValueError(
                f"{name} declares relations that no registry describes: {unknown[:10]}"
            )
        if not declared:
            raise ValueError(f"{name} declares no shortcut relation; it is not a changed variant")
        variant_info[name] = (data_dir, relations_by_id, declared)
    covered = set().union(*(d for _, _, d in variant_info.values()))
    uncovered = sorted(shortcut_names - covered)
    if uncovered:
        raise ValueError(f"Registry relations carried by no changed variant: {uncovered[:10]}")

    unchanged_pairs, unchanged_base_fp, unchanged_shortcut_fp = read_variant_edges(
        link_path=unchanged_dir / "link.dat",
        relations=unchanged_relations_by_id,
        base_names=set(base_relations),
        shortcut_names=shortcut_names,
    )
    channels = channel_catalog(base_relations, registry_rows)
    mappings = construct_block_relations(
        registry_rows=registry_rows,
        base_relations=base_relations,
        base_pairs=unchanged_pairs,
        channels=channels,
        layout=layout,
    )
    mapping_by_name = {m.name: m for m in mappings}

    variant_edges: dict[str, tuple[dict, dict, dict]] = {}
    for name, (data_dir, relations_by_id, declared) in variant_info.items():
        print(f"  [family] reading {name} link.dat ...", flush=True)
        pairs, base_fp, shortcut_fp = read_variant_edges(
            link_path=data_dir / "link.dat",
            relations=relations_by_id,
            base_names=set(base_relations),
            shortcut_names=shortcut_names,
        )
        if base_fp != unchanged_base_fp:
            differing = [b for b in sorted(base_relations) if base_fp.get(b) != unchanged_base_fp.get(b)]
            raise ValueError(f"{name} does not preserve the unchanged base relations: {differing[:10]}")
        for shortcut in sorted(shortcut_names):
            count = int(shortcut_fp.get(shortcut, empty_fingerprint()).get("count", 0))
            expected = int(mapping_by_name[shortcut].endpoint_count) if shortcut in declared else 0
            if count != expected:
                raise ValueError(
                    f"Physical shortcut count mismatch for {shortcut} in {name}: "
                    f"physical={count}, expected={expected}"
                )
        variant_edges[name] = (pairs, base_fp, shortcut_fp)

    plan_records, semantic_hashes, raw_hashes, context_hashes = [], set(), set(), set()
    family = [("unchanged", unchanged_dir, "base_composition", unchanged_pairs,
               unchanged_base_fp, unchanged_shortcut_fp, None)]
    for name, (data_dir, _, declared) in variant_info.items():
        pairs, base_fp, shortcut_fp = variant_edges[name]
        family.append((name, data_dir, "physical_shortcut", pairs, base_fp, shortcut_fp, tuple(sorted(declared))))
    for variant, data_dir, context_kind, pairs, base_fp, shortcut_fp, declared_names in family:
        base_src, base_dst, base_channel = build_base_message_arrays(
            base_pairs=pairs, channels=channels, total_nodes=layout.total,
        )
        semantic_program_hash = _semantic_hash(
            channels=channels, base_src=base_src, base_dst=base_dst,
            base_channel=base_channel, block_relations=mappings, layout=layout,
        )
        raw_graph_hash = combined_raw_graph_hash(data_dir)
        raw_link_hash = sha256_file(data_dir / "link.dat")
        context_payload = {
            "variant": variant,
            "context_kind": context_kind,
            "raw_graph_hash": raw_graph_hash,
            "raw_link_hash": raw_link_hash,
            "base_graph_hash": base_graph_hash(base_fp),
            "physical_shortcuts": shortcut_fp,
            "physical_shortcut_names": declared_names,
            "semantic_program_hash": semantic_program_hash,
            "mapping_contexts": {
                m.name: {"composition": list(m.composition), "activation": context_kind}
                for m in mappings
            },
        }
        plan = FreebaseBlockContextPlan(
            variant=variant, context_kind=context_kind, layout=layout, channels=channels,
            base_src=base_src, base_dst=base_dst, base_channel=base_channel,
            block_relations=mappings, raw_graph_hash=raw_graph_hash, raw_link_hash=raw_link_hash,
            base_graph_hash=base_graph_hash(base_fp), physical_shortcut_fingerprints=shortcut_fp,
            semantic_program_hash=semantic_program_hash,
            context_plan_hash=sha256_json(context_payload), source_dir=str(data_dir),
            physical_shortcut_names=declared_names,
        )
        plan.verify_runtime_context()
        plan.save(output_root / variant)
        record = plan.audit_dict()
        record["physical_shortcut_names"] = None if declared_names is None else list(declared_names)
        plan_records.append(record)
        semantic_hashes.add(semantic_program_hash)
        raw_hashes.add(raw_graph_hash)
        context_hashes.add(plan.context_plan_hash)
        print(f"  [family] {variant}: raw={raw_graph_hash[:12]} context={plan.context_plan_hash[:12]} "
              f"semantic={semantic_program_hash[:12]} shortcuts={'all' if declared_names is None else len(declared_names)}",
              flush=True)

    n = len(family)
    passed = len(raw_hashes) == n and len(context_hashes) == n and len(semantic_hashes) == 1
    audit = {
        "passed": passed,
        "family": [v[0] for v in family],
        "registry_paths": [str(Path(p).resolve()) for p in registry_paths],
        "registry_sha256": {str(Path(p).resolve()): sha256_file(Path(p)) for p in registry_paths},
        "mapping_interpretation": "authoritative_ordered_composition_with_block_recoverability_provenance",
        "endpoint_block_bijection_required": False,
        "endpoint_quotient_materialized": False,
        "physical_verification": "registry_count_per_declared_shortcut",
        "physical_shortcuts_used_as_context_only": True,
        "factorized_dependency_used_for_propagation": True,
        "num_channels": len(channels),
        "plans": plan_records,
    }
    write_json(output_root / "preprocessing_audit.json", audit)
    if not passed:
        raise AssertionError(f"Freebase family preprocessing failed: {audit}")
    return audit


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Preprocess genuine recoverability-conditional Freebase SlotGAT"
    )
    parser.add_argument("--unchanged-dir", type=Path, required=True)
    parser.add_argument("--changed-dir", type=Path, default=None,
                        help="Pair mode: the single changed variant (its registry is --registry).")
    parser.add_argument("--changed", action="append", default=[], metavar="NAME=DIR",
                        help="Family mode (repeatable): a changed variant and its HGB directory, "
                             "e.g. exact_3=/.../exact_3. Combine with one --registry per hop family.")
    parser.add_argument("--registry", type=Path, action="append", required=True,
                        help="Registry .jsonl (repeatable in family mode).")
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.changed:
        changed_dirs = {}
        for item in args.changed:
            if "=" not in item:
                raise SystemExit(f"--changed expects NAME=DIR, got {item!r}")
            name, path = item.split("=", 1)
            changed_dirs[name.strip()] = Path(path.strip())
        audit = preprocess_family(
            unchanged_dir=args.unchanged_dir,
            changed_dirs=changed_dirs,
            registry_paths=list(args.registry),
            output_root=args.output_root,
            overwrite=args.overwrite,
        )
    else:
        if args.changed_dir is None or len(args.registry) != 1:
            raise SystemExit("Pair mode needs --changed-dir and exactly one --registry")
        audit = preprocess_pair(
            unchanged_dir=args.unchanged_dir,
            exact_dir=args.changed_dir,
            registry_path=args.registry[0],
            output_root=args.output_root,
            overwrite=args.overwrite,
        )
    print("Freebase recoverability-conditional preprocessing passed.")
    for plan in audit["plans"]:
        print(
            f"  {plan['variant']}: raw={plan['raw_graph_hash'][:12]} "
            f"context={plan['context_plan_hash'][:12]} "
            f"semantic={plan['semantic_program_hash'][:12]} "
            f"base_messages={plan['base_message_count']} "
            f"path_records={plan['conditional_path_record_count']}"
        )


if __name__ == "__main__":
    main()
