def _splitmix64(values: np.ndarray) -> np.ndarray:
    values = values.astype(np.uint64, copy=False)
    values = values + np.uint64(0x9E3779B97F4A7C15)
    values = (values ^ (values >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
    values = (values ^ (values >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
    return values ^ (values >> np.uint64(31))


def pair_values(src: np.ndarray, dst: np.ndarray) -> np.ndarray:
    left = _splitmix64(src.astype(np.uint64, copy=False) ^ np.uint64(0x243F6A8885A308D3))
    right = _splitmix64(dst.astype(np.uint64, copy=False) ^ np.uint64(0x13198A2E03707344))
    return _splitmix64(left ^ np.left_shift(right, np.uint64(1)))


def empty_fingerprint() -> dict[str, int]:
    return {"count": 0, "xor64": 0, "sum64": 0}


def update_fingerprint(record: dict[str, int], src: np.ndarray, dst: np.ndarray) -> None:
    if src.size == 0:
        return
    values = pair_values(src, dst)
    record["count"] += int(values.size)
    record["xor64"] ^= int(np.bitwise_xor.reduce(values, dtype=np.uint64))
    # Perform the modular addition in Python integers.  NumPy's uint64 scalar
    # addition intentionally wraps but emits a RuntimeWarning on overflow.
    chunk_sum = int(np.sum(values, dtype=np.uint64))
    record["sum64"] = (int(record["sum64"]) + chunk_sum) & MASK64


def read_variant_edges(
    *,
    link_path: Path,
    relations: Mapping[int, RelationInfo],
    base_names: set[str],
    shortcut_names: set[str],
    chunk_size: int = 1_000_000,
) -> tuple[
    dict[str, tuple[np.ndarray, np.ndarray]],
    dict[str, dict[str, int]],
    dict[str, dict[str, int]],
]:
    base_lists: dict[str, tuple[list[int], list[int]]] = {
        name: ([], []) for name in base_names
    }
    base_fp = {name: empty_fingerprint() for name in base_names}
    shortcut_fp = {name: empty_fingerprint() for name in shortcut_names}
    chunks: dict[str, tuple[list[int], list[int]]] = defaultdict(lambda: ([], []))

    def flush(name: str) -> None:
        source_list, destination_list = chunks[name]
        if not source_list:
            return
        source = np.asarray(source_list, dtype=np.int64)
        destination = np.asarray(destination_list, dtype=np.int64)
        target = base_fp[name] if name in base_fp else shortcut_fp[name]
        update_fingerprint(target, source, destination)
        source_list.clear()
        destination_list.clear()

    with Path(link_path).open("r", encoding="utf-8") as handle:
        for line_no, raw in enumerate(handle, 1):
            if not raw.strip():
                continue
            parts = raw.rstrip("\n").split("\t")
            if len(parts) < 3:
                raise ValueError(f"Bad link.dat line {line_no}: {raw!r}")
            source, destination, relation_id = int(parts[0]), int(parts[1]), int(parts[2])
            relation = relations.get(relation_id)
            if relation is None:
                raise KeyError(
                    f"Unknown relation id {relation_id} in {link_path}:{line_no}"
                )
            name = relation.name
            if name in base_names:
                base_lists[name][0].append(source)
                base_lists[name][1].append(destination)
                chunks[name][0].append(source)
                chunks[name][1].append(destination)
            elif name in shortcut_names:
                chunks[name][0].append(source)
                chunks[name][1].append(destination)
            if name in chunks and len(chunks[name][0]) >= chunk_size:
                flush(name)
    for name in list(chunks):
        flush(name)

    base_pairs: dict[str, tuple[np.ndarray, np.ndarray]] = {}
    for name in sorted(base_names):
        source = np.asarray(base_lists[name][0], dtype=np.int64)
        destination = np.asarray(base_lists[name][1], dtype=np.int64)
        if source.size:
            order = np.lexsort((destination, source))
            source, destination = source[order], destination[order]
            keep = np.ones(source.size, dtype=bool)
            keep[1:] = (source[1:] != source[:-1]) | (
                destination[1:] != destination[:-1]
            )
            source, destination = source[keep], destination[keep]
        base_pairs[name] = (source, destination)
        fingerprint = empty_fingerprint()
        update_fingerprint(fingerprint, source, destination)
        base_fp[name] = fingerprint
    return base_pairs, base_fp, shortcut_fp


def base_graph_hash(base_fingerprints: Mapping[str, Mapping[str, int]]) -> str:
    return sha256_json(
        {
            name: {key: int(value) for key, value in sorted(fingerprint.items())}
            for name, fingerprint in sorted(base_fingerprints.items())
        }
    )


def build_base_message_arrays(
    *,
    base_pairs: Mapping[str, tuple[np.ndarray, np.ndarray]],
    channels: Sequence[ChannelRecord],
    total_nodes: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    lookup = {
        (record.semantic_relation, record.direction): int(record.channel)
        for record in channels
    }
    source_chunks: list[np.ndarray] = []
    destination_chunks: list[np.ndarray] = []
    channel_chunks: list[np.ndarray] = []
    for name in sorted(base_pairs):
        source, destination = base_pairs[name]
        for direction, left, right in (
            (1, source, destination),
            (-1, destination, source),
        ):
            source_chunks.append(left)
            destination_chunks.append(right)
            channel_chunks.append(
                np.full(left.size, lookup[(name, direction)], dtype=np.int64)
            )
    nodes = np.arange(total_nodes, dtype=np.int64)
    self_channel = next(record.channel for record in channels if record.kind == "self")
    source_chunks.append(nodes)
    destination_chunks.append(nodes)
    channel_chunks.append(np.full(total_nodes, self_channel, dtype=np.int64))
    source = np.concatenate(source_chunks)
    destination = np.concatenate(destination_chunks)
    channel = np.concatenate(channel_chunks)
    order = np.lexsort((source, channel, destination))
    return source[order], destination[order], channel[order]


