#!/usr/bin/env python3
r"""Recoverability-conditional structural bias for Freebase SlotGAT.

The Freebase variants preserve every base edge and optionally materialize
shortcut relations generated by ordered base-relation compositions.  The
supplied MAGNN registry provides the authoritative ordered composition, typed
endpoints, and endpoint count for every shortcut.  It does not provide
endpoint quotient memberships.

Consequently this module does not infer paired complete-bipartite fibers from
the shortcut endpoint matrix.  It keeps the variant-specific physical context
distinct and represents each registered mapping as a factorized semantic path
channel.  The unchanged variant activates the channel from the base-composition
context; the changed variant activates the same channel after verifying the
physical shortcut schema and count.  Propagation follows the ordered dependency
and never expands the potentially tens of millions of shortcut endpoint pairs
at training time.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

import numpy as np
import scipy.sparse as sp

MASK64 = (1 << 64) - 1


@dataclass(frozen=True)
class RelationInfo:
    rid: int
    start_type: int
    end_type: int
    name: str


@dataclass(frozen=True)
class NodeTypeLayout:
    counts: tuple[int, ...]
    offsets: tuple[int, ...]
    names: tuple[str, ...]

    @property
    def total(self) -> int:
        return int(sum(self.counts))

    def global_nodes(self, node_type: int) -> np.ndarray:
        start = int(self.offsets[node_type])
        return np.arange(start, start + int(self.counts[node_type]), dtype=np.int64)

    def to_json(self) -> dict[str, Any]:
        return {
            "counts": list(self.counts),
            "offsets": list(self.offsets),
            "names": list(self.names),
            "total": self.total,
        }

    @classmethod
    def from_json(cls, payload: Mapping[str, Any]) -> "NodeTypeLayout":
        return cls(
            counts=tuple(int(x) for x in payload["counts"]),
            offsets=tuple(int(x) for x in payload["offsets"]),
            names=tuple(str(x) for x in payload["names"]),
        )


@dataclass(frozen=True)
class ChannelRecord:
    channel: int
    semantic_relation: str
    direction: int
    kind: str

    def to_json(self) -> dict[str, Any]:
        return {
            "channel": int(self.channel),
            "semantic_relation": self.semantic_relation,
            "direction": int(self.direction),
            "kind": self.kind,
        }


@dataclass
class BlockRelation:
    """One registered semantic mapping represented as a factorized path.

    The class name is retained for compatibility with the first package.  No
    endpoint quotient is assumed; ``hop_recovery`` stores provenance entries
    when detailed mining diagnostics are not present in the registry.
    """

    name: str
    composition: tuple[str, ...]
    start_type: int
    end_type: int
    forward_channel: int
    reverse_channel: int
    forward_steps: tuple[int, ...]
    reverse_steps: tuple[int, ...]
    forward_support: np.ndarray
    reverse_support: np.ndarray
    endpoint_count: int
    endpoint_fingerprint: dict[str, int]
    hop_recovery: tuple[dict[str, Any], ...]

    @property
    def num_blocks(self) -> int:
        # Compatibility field: the meaningful local units are composition
        # positions, not endpoint quotient blocks.
        return len(self.hop_recovery)

    def semantic_descriptor(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "composition": list(self.composition),
            "start_type": int(self.start_type),
            "end_type": int(self.end_type),
            "forward_channel": int(self.forward_channel),
            "reverse_channel": int(self.reverse_channel),
            "forward_steps": list(self.forward_steps),
            "reverse_steps": list(self.reverse_steps),
            "forward_support_hash": sha256_array(self.forward_support),
            "reverse_support_hash": sha256_array(self.reverse_support),
            "forward_support_count": int(self.forward_support.size),
            "reverse_support_count": int(self.reverse_support.size),
            "endpoint_count": int(self.endpoint_count),
            "endpoint_fingerprint": dict(self.endpoint_fingerprint),
            "hop_recovery": [dict(row) for row in self.hop_recovery],
            "mapping_semantics": "authoritative_ordered_composition",
        }


@dataclass
class FreebaseBlockContextPlan:
    """Variant-specific context consumed by the conditional SlotGAT model."""

    variant: str
    context_kind: str
    layout: NodeTypeLayout
    channels: tuple[ChannelRecord, ...]
    base_src: np.ndarray
    base_dst: np.ndarray
    base_channel: np.ndarray
    block_relations: tuple[BlockRelation, ...]
    raw_graph_hash: str
    raw_link_hash: str
    base_graph_hash: str
    physical_shortcut_fingerprints: dict[str, dict[str, int]]
    semantic_program_hash: str
    context_plan_hash: str
    source_dir: str
    # Shortcut relations this variant's schema (info.dat) actually declares. In a
    # multi-variant FAMILY (unchanged / exact_2 / exact_3 / union_exact_2_3)
    # the block catalog is the union of every registry, so exact_2 legitimately carries
    # zero edges for the 3-hop mappings. ``None`` = every mapping (the historical pair
    # behaviour), which older plans on disk still get.
    physical_shortcut_names: tuple[str, ...] | None = None

    @property
    def num_channels(self) -> int:
        return len(self.channels)

    @property
    def self_channel(self) -> int:
        matches = [record.channel for record in self.channels if record.kind == "self"]
        if len(matches) != 1:
            raise RuntimeError("Expected exactly one self channel")
        return int(matches[0])

    @property
    def base_message_count(self) -> int:
        return int(self.base_src.size)

    @property
    def quotient_message_record_count(self) -> int:
        # Compatibility name.  There is one factorized path record for each
        # supported endpoint node in each direction.
        return int(
            sum(
                relation.forward_support.size + relation.reverse_support.size
                for relation in self.block_relations
            )
        )

    def audit_dict(self) -> dict[str, Any]:
        return {
            "variant": self.variant,
            "context_kind": self.context_kind,
            "source_dir": self.source_dir,
            "raw_graph_hash": self.raw_graph_hash,
            "raw_link_hash": self.raw_link_hash,
            "base_graph_hash": self.base_graph_hash,
            "semantic_program_hash": self.semantic_program_hash,
            "context_plan_hash": self.context_plan_hash,
            "num_channels": self.num_channels,
            "base_message_count": self.base_message_count,
            "conditional_path_record_count": self.quotient_message_record_count,
            "physical_shortcut_fingerprints": self.physical_shortcut_fingerprints,
            "layout": self.layout.to_json(),
            "channels": [record.to_json() for record in self.channels],
            "block_relations": [relation.semantic_descriptor() for relation in self.block_relations],
            "materialized_shared_graph": False,
            "materialized_shortcut_endpoint_messages": False,
            "model_facing_input": "distinct_raw_recoverability_context_plan",
            "operator": "factorized_recoverability_conditional_slotgat_v2",
        }

    def verify_runtime_context(self) -> None:
        if self.context_kind == "base_composition":
            if self.variant != "unchanged":
                raise ValueError(
                    "base_composition context is reserved for the unchanged variant"
                )
            unexpected = [
                relation.name
                for relation in self.block_relations
                if int(
                    self.physical_shortcut_fingerprints.get(
                        relation.name, empty_fingerprint()
                    ).get("count", 0)
                )
                != 0
            ]
            if unexpected:
                raise ValueError(
                    "Unchanged context unexpectedly contains shortcut relations: "
                    + ", ".join(unexpected[:10])
                )
        elif self.context_kind == "physical_shortcut":
            bad = []
            declared = (
                None if self.physical_shortcut_names is None
                else set(self.physical_shortcut_names)
            )
            for relation in self.block_relations:
                observed = self.physical_shortcut_fingerprints.get(
                    relation.name, empty_fingerprint()
                )
                count = int(observed.get("count", 0))
                if declared is not None and relation.name not in declared:
                    # not part of this variant's schema: must be absent, not verified
                    if count != 0:
                        bad.append(relation.name)
                    continue
                if count != int(relation.endpoint_count):
                    bad.append(relation.name)
            if declared is not None and not declared:
                raise ValueError("physical_shortcut context declares no shortcut relations")
            if bad:
                raise ValueError(
                    "Physical shortcut context failed endpoint verification for: "
                    + ", ".join(bad[:10])
                )
        else:
            raise ValueError(f"Unsupported Freebase context kind: {self.context_kind}")

    def save(self, output_dir: Path) -> None:
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        np.save(output_dir / "base_src.npy", np.asarray(self.base_src, dtype=np.int64))
        np.save(output_dir / "base_dst.npy", np.asarray(self.base_dst, dtype=np.int64))
        np.save(
            output_dir / "base_channel.npy",
            np.asarray(self.base_channel, dtype=np.int64),
        )
        relation_dir = output_dir / "mappings"
        relation_dir.mkdir(parents=True, exist_ok=True)
        relation_manifest = []
        for index, relation in enumerate(self.block_relations):
            filename = f"{index:03d}_{safe_name(relation.name)}.npz"
            np.savez(
                relation_dir / filename,
                forward_support=np.asarray(relation.forward_support, dtype=np.int64),
                reverse_support=np.asarray(relation.reverse_support, dtype=np.int64),
            )
            row = relation.semantic_descriptor()
            row["file"] = str(Path("mappings") / filename)
            relation_manifest.append(row)
        manifest = self.audit_dict()
        manifest["block_relations"] = relation_manifest
        manifest["physical_shortcut_names"] = (
            None if self.physical_shortcut_names is None else list(self.physical_shortcut_names)
        )
        write_json(output_dir / "context_plan.json", manifest)

    @classmethod
    def load(cls, directory: Path) -> "FreebaseBlockContextPlan":
        directory = Path(directory)
        manifest = json.loads((directory / "context_plan.json").read_text())
        channels = tuple(
            ChannelRecord(
                channel=int(row["channel"]),
                semantic_relation=str(row["semantic_relation"]),
                direction=int(row["direction"]),
                kind=str(row["kind"]),
            )
            for row in manifest["channels"]
        )
        relations = []
        for row in manifest["block_relations"]:
            arrays = np.load(directory / row["file"])
            relations.append(
                BlockRelation(
                    name=str(row["name"]),
                    composition=tuple(str(x) for x in row["composition"]),
                    start_type=int(row["start_type"]),
                    end_type=int(row["end_type"]),
                    forward_channel=int(row["forward_channel"]),
                    reverse_channel=int(row["reverse_channel"]),
                    forward_steps=tuple(int(x) for x in row["forward_steps"]),
                    reverse_steps=tuple(int(x) for x in row["reverse_steps"]),
                    forward_support=np.asarray(arrays["forward_support"], dtype=np.int64),
                    reverse_support=np.asarray(arrays["reverse_support"], dtype=np.int64),
                    endpoint_count=int(row["endpoint_count"]),
                    endpoint_fingerprint={
                        str(key): int(value)
                        for key, value in row["endpoint_fingerprint"].items()
                    },
                    hop_recovery=tuple(dict(item) for item in row["hop_recovery"]),
                )
            )
        return cls(
            variant=str(manifest["variant"]),
            context_kind=str(manifest["context_kind"]),
            layout=NodeTypeLayout.from_json(manifest["layout"]),
            channels=channels,
            base_src=np.load(directory / "base_src.npy", mmap_mode="r"),
            base_dst=np.load(directory / "base_dst.npy", mmap_mode="r"),
            base_channel=np.load(directory / "base_channel.npy", mmap_mode="r"),
            block_relations=tuple(relations),
            raw_graph_hash=str(manifest["raw_graph_hash"]),
            raw_link_hash=str(manifest["raw_link_hash"]),
            base_graph_hash=str(manifest["base_graph_hash"]),
            physical_shortcut_fingerprints={
                str(name): {str(key): int(value) for key, value in fp.items()}
                for name, fp in manifest.get(
                    "physical_shortcut_fingerprints", {}
                ).items()
            },
            semantic_program_hash=str(manifest["semantic_program_hash"]),
            context_plan_hash=str(manifest["context_plan_hash"]),
            source_dir=str(manifest.get("source_dir", "")),
            physical_shortcut_names=(
                None if manifest.get("physical_shortcut_names") is None
                else tuple(str(v) for v in manifest["physical_shortcut_names"])
            ),
        )


